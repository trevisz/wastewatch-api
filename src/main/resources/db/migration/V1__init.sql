CREATE TABLE collection_point (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  name VARCHAR2(255) NOT NULL,
  location VARCHAR2(255) NOT NULL,
  capacityKg NUMBER(10,2) NOT NULL,
  currentLevelKg NUMBER(10,2) NOT NULL,
  thresholdPercent NUMBER(3) NOT NULL
);

CREATE TABLE pickup (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  collection_point_id NUMBER NOT NULL,
  scheduledAt TIMESTAMP WITH TIME ZONE NOT NULL,
  status VARCHAR2(32) NOT NULL,
  CONSTRAINT fk_pickup_cp FOREIGN KEY (collection_point_id) REFERENCES collection_point(id)
);
